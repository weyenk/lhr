import { build } from 'esbuild';
import { build as viteBuild } from 'vite';
import { readFileSync, readdirSync, writeFileSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const shared = {
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  packages: 'external',
  sourcemap: false,
};

// Build the client SPA first, then inline its output into a generated module that
// src/server.ts imports and esbuild bundles alongside the server code. This is
// deliberate: Vercel's includeFiles/file-tracing did not reliably package
// client/dist into the deployed function (verified in production — the directory
// was missing from /var/task at runtime despite the build producing it), causing
// every page load to 404. Inlining the assets as base64 in the JS bundle itself
// removes any dependency on Vercel's packaging heuristics — esbuild's own
// bundling of local imports is what actually ships this file, the same mechanism
// already relied on for every other server-side module.
await viteBuild({ root: fileURLToPath(new URL('../client', import.meta.url)) });

const CONTENT_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.json': 'application/json; charset=utf-8',
};

const distDir = fileURLToPath(new URL('../client/dist', import.meta.url));
const assets = {};

function walk(dir, urlPrefix) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    const urlPath = `${urlPrefix}${entry.name}`;
    if (entry.isDirectory()) {
      walk(fullPath, `${urlPath}/`);
      continue;
    }
    const ext = path.extname(entry.name);
    assets[urlPath] = {
      contentType: CONTENT_TYPES[ext] ?? 'application/octet-stream',
      base64: readFileSync(fullPath).toString('base64'),
    };
  }
}

if (statSync(distDir, { throwIfNoEntry: false })?.isDirectory()) {
  walk(distDir, '/');
}

if (!assets['/index.html']) {
  throw new Error(`client build did not produce ${distDir}/index.html — cannot generate clientAssets`);
}

const generatedPath = fileURLToPath(new URL('../src/clientAssets.generated.ts', import.meta.url));
writeFileSync(
  generatedPath,
  `// Auto-generated by scripts/bundle.mjs at build time — do not edit by hand.\n` +
    `export interface ClientAsset {\n  contentType: string;\n  base64: string;\n}\n\n` +
    `export const clientAssets: Record<string, ClientAsset> = ${JSON.stringify(assets, null, 2)};\n`,
);

await Promise.all([
  build({ ...shared, entryPoints: ['api/index.ts'], outfile: 'dist/api/index.js' }),
  build({ ...shared, entryPoints: ['src/server.ts'], outfile: 'dist/src/server.js' }),
]);
