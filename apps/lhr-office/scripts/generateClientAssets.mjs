import { build as viteBuild } from 'vite';
import { readFileSync, readdirSync, writeFileSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const CONTENT_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.json': 'application/json; charset=utf-8',
};

function walk(dir, urlPrefix, assets) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    const urlPath = `${urlPrefix}${entry.name}`;
    if (entry.isDirectory()) {
      walk(fullPath, `${urlPath}/`, assets);
      continue;
    }
    const ext = path.extname(entry.name);
    assets[urlPath] = {
      contentType: CONTENT_TYPES[ext] ?? 'application/octet-stream',
      base64: readFileSync(fullPath).toString('base64'),
    };
  }
}

// Build the client SPA, then inline its output into a generated module that src/server.ts
// imports directly. This is deliberate: Vercel's includeFiles/file-tracing did not reliably
// package client/dist into the deployed function (verified in production — the directory was
// missing from /var/task at runtime despite the build producing it), causing every page load to
// 404. Inlining the assets as base64 removes any dependency on Vercel's packaging heuristics —
// and it's also what server.ts reads from locally, so `npm run dev` needs this step too, not
// just the production build in scripts/bundle.mjs.
export async function generateClientAssets() {
  await viteBuild({ root: fileURLToPath(new URL('../client', import.meta.url)) });

  const distDir = fileURLToPath(new URL('../client/dist', import.meta.url));
  const assets = {};
  if (statSync(distDir, { throwIfNoEntry: false })?.isDirectory()) {
    walk(distDir, '/', assets);
  }

  if (!assets['/index.html']) {
    throw new Error(`client build did not produce ${distDir}/index.html — cannot generate clientAssets`);
  }

  const generatedPath = fileURLToPath(new URL('../src/clientAssets.generated.ts', import.meta.url));
  writeFileSync(
    generatedPath,
    `// Auto-generated by scripts/generateClientAssets.mjs at build time — do not edit by hand.\n` +
      `export interface ClientAsset {\n  contentType: string;\n  base64: string;\n}\n\n` +
      `export const clientAssets: Record<string, ClientAsset> = ${JSON.stringify(assets, null, 2)};\n`,
  );
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await generateClientAssets();
}
